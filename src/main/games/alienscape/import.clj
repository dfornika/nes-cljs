(ns games.alienscape.import
  "Turns the pictures in Hexany's Alienscape (resources/assets/hexanys-alienscape,
  CC0, by Hexany Ives) into the data in games.alienscape.art.

    npm run import:alienscape      (or: clojure -M -m games.alienscape.import)

  Run it again if the pictures, or the choices below, change; the file it
  writes is kept in the repository, so building the game doesn't need this."
  (:require [clojure.java.io :as io]
            [clojure.pprint :as pprint]
            [clojure.string :as str]
            [gamedev-toolkit.png :as png]))

(def pack "resources/assets/hexanys-alienscape/")
(def output "src/main/games/alienscape/art.cljc")

(def backdrop 0x0F)

(def color-choices
  "Colors in the pack whose nearest match in the emulator's table isn't
  the best-looking one."
  {[0x2c 0x00 0x6e] 0x03})    ; a dark indigo: the nearest was a dark blue-green

(def rooms
  "The example screens to turn into rooms."
  {:arena "example_2.png"})

(def creatures
  "Animations to turn into sprites: [file frame-width]"
  {:biter ["Animations/Creatures/biter_transparent.png" 16]
   :orb   ["Animations/Tiles/big_orb_transparent.png" 16]})

(defn- colors-of [file]
  (png/to-nes-colors (png/read-image (str pack file)) backdrop color-choices))

(defn- sprite [[file width]]
  (let [colors (colors-of file)
        [palette & more] (png/palettes-for [colors] backdrop)]
    (when more
      (throw (ex-info (str file " needs more than one sprite palette") {})))
    {:palette palette
     :frames (png/frames colors backdrop palette width)}))

(defn- form
  "A (def ...) as text, with a long vector's items one to a line."
  [name doc value lines?]
  (str "(def " name "\n  " (pr-str doc) "\n  "
       (if lines?
         (str "[" (str/join "\n   " (map pr-str value)) "]")
         (str/trim (with-out-str (pprint/pprint value))))
       ")\n"))

(defn art
  "Read the pack's pictures and work everything out: {:palettes :tiles
  :rooms :sprites}, as they're written to games.alienscape.art, plus
  :repainted {room pixels}."
  []
  (let [pictures (into {} (for [[k file] rooms] [k (colors-of file)]))
        palettes (png/palettes-for (vals pictures) backdrop)
        _ (when (> (count palettes) 4)
            (throw (ex-info (str "These pictures need " (count palettes) " background palettes; there are four") {:palettes palettes})))
        ;; tile 0 is blank, whatever else there is
        blank (vec (repeat 8 "........"))
        [tiles made] (reduce (fn [[tiles made] [k colors]]
                               (let [s (png/screen colors backdrop palettes tiles)]
                                 [(:tiles s) (assoc made k (dissoc s :tiles))]))
                             [[blank] {}]
                             pictures)]
    {:palettes palettes
     :tiles tiles
     :rooms (into {} (for [[k s] made] [k (dissoc s :repainted)]))
     :repainted (into {} (for [[k s] made] [k (:repainted s)]))
     :sprites (into {} (for [[k spec] creatures] [k (sprite spec)]))}))

(defn -main [& _]
  (let [{:keys [palettes tiles rooms repainted sprites]} (art)]
    (doseq [[k n] repainted]
      (println (name k) "-" n "pixels repainted to fit one palette per 16x16 area"))
    (println (count tiles) "background tiles," (count palettes) "background palettes:" palettes)
    (doseq [[k {:keys [palette frames]}] sprites]
      (println (name k) "-" (count frames) "frames, palette" palette))
    (spit output
          (str "(ns games.alienscape.art\n"
               "  \"The art for games.alienscape, as data: tiles drawn as text, and which\n"
               "  tile goes where. From Hexany's Alienscape by Hexany Ives (CC0; see\n"
               "  resources/assets/hexanys-alienscape).\n\n"
               "  GENERATED by games.alienscape.import (npm run import:alienscape) from\n"
               "  the pack's pictures. Change that, or the pictures, not this file.\")\n\n"
               (form "backdrop" "The color behind everything: a NES color number." backdrop false) "\n"
               (form "background-palettes" "Three NES colors each, darkest first; a tile's 1 2 3 pick from one of them." palettes false) "\n"
               (form "tiles" "The background's distinct 8x8 tiles, as drawings. Tile 0 is blank." tiles true) "\n"
               (form "rooms"
                     "Each room: :grid is which of `tiles` goes where (960 numbers, 32 to a row), and :block-palettes which of `background-palettes` each 16x16 area uses (240 numbers, 16 to a row)."
                     rooms false) "\n"
               (form "sprites" "Creatures: each has a :palette (three NES colors) and :frames, 16x16 drawings." sprites false)))
    (println "wrote" output)))
